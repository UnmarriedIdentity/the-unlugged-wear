// Post-processes `drizzle-kit pull` output so it typechecks and runs under
// Node's native TypeScript (tests) as well as Next.js:
//  - drop the SQL migration + meta folder (db/migrate/*.sql own the schema)
//  - map Postgres tsvector columns (drizzle prints `unknown(...)`)
//  - add .ts extensions to relative imports
import { readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../src/platform/db/generated/', import.meta.url).pathname;
for (const f of readdirSync(dir)) if (f.endsWith('.sql') || f === 'meta') rmSync(join(dir, f), { recursive: true, force: true });

const header = '// GENERATED by `pnpm db:types` (drizzle-kit pull + scripts/fix-generated.mjs). Do not edit.\n';
for (const name of ['schema.ts', 'relations.ts']) {
  const path = join(dir, name);
  let text = readFileSync(path, 'utf8');
  text = text.replace(/^\/\/ GENERATED[^\n]*\n/, '');
  text = text.replace(/\s*\/\/ TODO: failed to parse database type 'tsvector'\n/g, '\n');
  text = text.replace(/unknown\("([a-z_]+)"\)/g, 'tsvector("$1")');
  if (text.includes('tsvector(') && !text.includes("from '../types.ts'")) {
    text = text.replace(/(import \{ sql \} from "drizzle-orm"\n)/, `$1import { tsvector } from '../types.ts';\n`);
  }
  text = text.replace(/from "\.\/schema"/g, 'from "./schema.ts"');
  // drizzle-kit prints an empty-string default as .default(') — restore ''.
  text = text.replace(/\.default\('\)/g, ".default('')");
  writeFileSync(path, header + text);
}
console.log('generated schema post-processed');
