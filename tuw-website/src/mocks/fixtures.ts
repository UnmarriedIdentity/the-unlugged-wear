function partnerSpecTable(
  kind: string,
  sizeRange: string,
  colourCount: number,
  weightGrams: number,
  printAreas: string,
  weightBasis: string
): ProductSpecTable {
  return {
    title: 'Product Specifications',
    description: 'Taken from our print partner\'s base-product sheet. Final size chart to follow.',
    columns: [
      { key: 'spec', label: 'Specification', align: 'left' },
      { key: 'value', label: 'Detail', align: 'left' },
    ],
    rows: [
      { spec: 'Product', value: kind.charAt(0).toUpperCase() + kind.slice(1) },
      { spec: 'Sizes', value: sizeRange },
      { spec: 'Colours offered', value: String(colourCount) },
      { spec: 'Approximate weight', value: `${weightGrams} g (${weightBasis})` },
      { spec: 'Print areas', value: printAreas },
      { spec: 'Made', value: 'Printed after you order by our print partner in Tiruppur, India' },
      { spec: 'Fabric composition', value: 'To be confirmed (draft)' },
    ],
  };
}

